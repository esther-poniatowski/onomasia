"""
Contracts of Onomasia: the documents that it reads from other tools and writes for them.

Onomasia owns five contracts. It reads two documents generated by other tools, the denotes targets
and the scope table, each validated against the schema of its contract. It writes
three documents, the macro table, the macro lookup and the term table. Every document names its
contract under `_schema` and the sources of its records. A written document also lists under
`inputs` the records of other repositories imported into it. A unit is carried as a logical target.
A target of the denotes targets without repository names a unit of the consumer, so Onomasia
normalizes it by the repository of the consumer; the units are then matched with the entries by
their normalized targets.

Classes
-------
ScopeTable
    Ancestors and descendants of each audience, read from a scope table.

Functions
---------
read_signatures(paths, root, validator, sink, repository) -> dict[Target, TargetSignature]
    Read the arguments of each unit from documents of denotes targets.
read_scope_table(path, root, validator, sink) -> ScopeTable | None
    Read a scope table.
macro_table_document(table, sources) -> dict
    Write a macro table as a document of its contract.
macro_lookup_document(table, sources) -> dict
    Write the macro lookup of a table built from base notations, ordered by target.
term_table_document(composition, sources, default_status) -> dict
    Write the terms of a composed glossary as a document of its contract.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Sequence, cast

from anagraphe_read import Target
import yaml

from .composition import Composition
from .issues import IssueSink
from .provenance import Input, Source
from .records.model import Record, Term
from .records.validation import SchemaValidator
from .typography.table import MacroTable, TargetSignature

DENOTES_TARGETS = "onomasia:denotes-targets@3"
"""Contract of the units that a key `denotes` may name, with their arguments."""

SCOPE_TABLE = "onomasia:scope-table@1"
"""Contract of the ancestors and the descendants of each audience."""

MACRO_TABLE = "onomasia:macro-table@2"
"""Contract of the macros of a composition of notations."""

MACRO_LOOKUP = "onomasia:macro-lookup@2"
"""Contract of the macro name of each unit."""

TERM_TABLE = "onomasia:term-table@1"
"""Contract of the terms of a composed glossary."""

CONTRACT_SCHEMAS = {
    DENOTES_TARGETS: "denotes-targets.schema.yml",
    SCOPE_TABLE: "scope-table.schema.yml",
    MACRO_TABLE: "macro-table.schema.yml",
    MACRO_LOOKUP: "macro-lookup.schema.yml",
    TERM_TABLE: "term-table.schema.yml",
}
"""Packaged schema of each contract."""


@dataclass(frozen=True)
class ScopeTable:
    """
    Ancestors and descendants of each audience, read from a scope table.

    Attributes
    ----------
    audiences : Mapping[str, frozenset[str]]
        Audiences related to each audience: itself, its ancestors and its descendants.
    """

    audiences: Mapping[str, frozenset[str]]

    def related(self, audience: str) -> frozenset[str]:
        """
        Audiences whose lexical rules bind a text bound to `audience`, itself included.

        Examples
        --------
        >>> ScopeTable({"ml": frozenset({"ml", "science"})}).related("ml") == {"ml", "science"}
        True
        """
        return self.audiences.get(audience, frozenset({audience}))


def _item_of(pointer: str, collection: str) -> str | None:
    """Return the key of the item of `collection` holding a violation, None outside every item.

    Examples
    --------
    >>> _item_of("/targets/2/arguments", "targets"), _item_of("/sources/0", "targets")
    ('2', None)
    """
    prefix = f"/{collection}/"
    if not pointer.startswith(prefix):
        return None
    return pointer[len(prefix) :].split("/", 1)[0]


@dataclass(frozen=True)
class _Document:
    """An input document that its header admits, with the keys of its invalid items."""

    resource: str
    data: Mapping[str, object]
    invalid: frozenset[str]


@dataclass(frozen=True)
class _Reader:
    """Reader of the input documents under one root, reporting each defect to one sink."""

    root: Path
    validator: SchemaValidator
    sink: IssueSink

    def read(self, path: Path, contract: str, collection: str) -> _Document | None:
        """Read and validate one input document, reporting each defect on its path.

        A violation inside one item of `collection` reports that item as `invalid-item`, and the
        item is skipped; the other items stay. A violation outside every item, in the header of
        the document, reports `invalid-contract`, and the whole document is skipped.
        """
        root = self.root
        resource = path.relative_to(root).as_posix() if path.is_relative_to(root) else str(path)
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
        except (OSError, yaml.YAMLError) as error:
            self.sink.report("invalid-contract", resource, "", f"cannot read the document: {error}")
            return None
        invalid: set[str] = set()
        header = False
        for pointer, message in self.validator.contract_errors(CONTRACT_SCHEMAS[contract], data):
            item = _item_of(pointer, collection)
            if item is None:
                self.sink.report("invalid-contract", resource, pointer, message)
                header = True
            else:
                self.sink.report("invalid-item", resource, pointer, message)
                invalid.add(item)
        if header:
            return None
        return _Document(resource, cast(Mapping[str, object], data), frozenset(invalid))


def _slot_problem(item: Mapping[str, object]) -> tuple[str, str] | None:
    """Return the field and the statement of a slot that the arguments of a unit cannot hold."""
    arguments = cast(int, item["arguments"])
    for field_name in ("bound", "list"):
        slot = item.get(field_name)
        if isinstance(slot, int) and slot > arguments:
            return field_name, f"the slot {slot} exceeds the {arguments} arguments of the unit"
    if item.get("bound") is not None and item.get("bound") == item.get("list"):
        return "list", "one argument cannot both bind a variable and take a list of items"
    return None


def _signature(item: Mapping[str, object]) -> TargetSignature:
    """Return the arguments of a unit from a valid item of the denotes targets."""
    bound, items = item.get("bound"), item.get("list")
    return TargetSignature(
        arguments=int(cast(int, item["arguments"])),
        bound=int(cast(int, bound)) if bound is not None else None,
        items=int(cast(int, items)) if items is not None else None,
    )


def read_signatures(
    paths: Sequence[Path],
    root: Path,
    validator: SchemaValidator,
    sink: IssueSink,
    *,
    repository: str | None,
) -> dict[Target, TargetSignature]:
    """Read the arguments of each unit from documents of denotes targets, keyed by the normalized
    target of the unit, the later document winning.

    A target without repository names a unit of the consumer, so it is normalized by
    ``repository``, the identifier of the repository of the consumer; it stays without repository
    when the consumer declares none, as the targets of its entries do. An invalid item is reported
    and skipped, and the other items of its document stay."""
    reader = _Reader(root, validator, sink)
    signatures: dict[Target, TargetSignature] = {}
    for path in paths:
        document = reader.read(path, DENOTES_TARGETS, "targets")
        if document is None:
            continue
        items = cast(Sequence[Mapping[str, object]], document.data.get("targets", ()))
        for index, item in enumerate(items):
            if str(index) in document.invalid:
                continue
            problem = _slot_problem(item)
            if problem is not None:
                pointer = f"/targets/{index}/{problem[0]}"
                sink.report("invalid-item", document.resource, pointer, problem[1])
                continue
            target = Target.parse(dict(cast(Mapping[str, str], item["target"])))
            signatures[target.normalized(repository)] = _signature(item)
    return signatures


def read_scope_table(
    path: Path, root: Path, validator: SchemaValidator, sink: IssueSink
) -> ScopeTable | None:
    """Read a scope table, or None when its header is invalid; an invalid audience is reported
    and skipped."""
    document = _Reader(root, validator, sink).read(path, SCOPE_TABLE, "audiences")
    if document is None:
        return None
    audiences = cast(Mapping[str, Mapping[str, Sequence[str]]], document.data["audiences"])
    return ScopeTable(
        {
            audience: frozenset({audience, *scope["ancestors"], *scope["descendants"]})
            for audience, scope in audiences.items()
            if audience not in document.invalid
        }
    )


def _header(
    contract: str, sources: tuple[Source, ...], inputs: tuple[Input, ...]
) -> dict[str, object]:
    """Common fields of every document written by Onomasia; the optional block `inputs` is
    written when a record of another repository is imported."""
    header: dict[str, object] = {
        "_schema": contract,
        "sources": [source.to_data() for source in sources],
    }
    if inputs:
        header["inputs"] = [item.to_data() for item in inputs]
    return header


def _target(target: Target | None) -> dict[str, str] | None:
    """Write a normalized target as its mapping, None for an entry denoting no unit."""
    return target.as_mapping() if target is not None else None


def macro_table_document(table: MacroTable, sources: tuple[Source, ...]) -> dict[str, object]:
    """Write a macro table as a document of its contract."""
    document = _header(MACRO_TABLE, sources, table.inputs)
    document["notations"] = list(table.notations)
    document["overlays"] = list(table.overlays)
    document["entries"] = [
        {
            "id": macro.identifier,
            "notation": macro.notation,
            "target": _target(macro.target),
            "name": macro.name,
            "body": macro.body,
            "arity": macro.arity,
            "entry": macro.entry_argument,
            "binder": macro.binder,
            "list": macro.items,
            "separator": macro.separator,
            "class": macro.typographic_class,
        }
        for macro in table.macros
    ]
    return document


def macro_lookup_document(table: MacroTable, sources: tuple[Source, ...]) -> dict[str, object]:
    """Write the macro lookup of a table of base notations, one item per target, ordered by the
    repository, the identifier and the unit of the target; an entry denoting no unit has no
    item."""
    document = _header(MACRO_LOOKUP, sources, table.inputs)
    document["notations"] = list(table.notations)
    named = [(macro.target, macro.name) for macro in table.macros if macro.target is not None]
    document["targets"] = [
        {"target": target.as_mapping(), "name": name}
        for target, name in sorted(
            named,
            key=lambda item: (item[0].repository or "", item[0].id or "", item[0].unit or ""),
        )
    ]
    return document


def _gloss(text: str, record: Record, pointer: str) -> dict[str, object]:
    """Locate a gloss: the path of its record within its repository and its pointer, with the
    repository and the commit of a record read from another repository."""
    origin = record.origin
    gloss: dict[str, object] = {
        "text": text,
        "resource": origin.path if origin is not None else record.resource,
        "pointer": pointer,
    }
    if origin is not None:
        gloss["repository"] = origin.repository
        gloss["commit"] = origin.commit
    return gloss


def term_table_document(
    composition: Composition, sources: tuple[Source, ...], default_status: str
) -> dict[str, object]:
    """Write the terms of a composed glossary, sorted by identifier, as a contract document."""
    document = _header(TERM_TABLE, sources, composition.inputs())
    document["glossary"] = composition.record.identifier
    terms: list[dict[str, object]] = []
    for identifier, visible in sorted(composition.sections.get("terms", {}).items()):
        term = visible.entry
        assert isinstance(term, Term)
        forms: list[object] = [term.label]
        forms.extend({"regex": form.text} if form.regex else form.text for form in term.forms)
        forms.extend(alternative.text for alternative in term.alternatives)
        terms.append(
            {
                "id": identifier,
                "forms": forms,
                "status": term.status or default_status,
                "gloss": _gloss(term.gloss, visible.record, f"/terms/{identifier}/gloss"),
            }
        )
    document["terms"] = terms
    return document
