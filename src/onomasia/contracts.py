"""
Contracts of Onomasia: the documents that it reads from other tools and writes for them.

Onomasia owns five contracts. It reads two documents, the denotes targets generated by Gnomon and
the scope table generated by Ekthesis, each validated against the schema of its contract. It
writes three documents, the macro table, the macro lookup and the term table, each naming its
contract and the sources of its records.

Classes
-------
ScopeTable
    Ancestors and descendants of each audience, read from a scope table.

Functions
---------
read_signatures(paths, root, validator, sink) -> dict[str, TargetSignature]
    Read the arguments of each unit from documents of denotes targets.
read_scope_table(path, root, validator, sink) -> ScopeTable | None
    Read a scope table.
macro_table_document(table, sources) -> dict
    Write a macro table as a document of its contract.
macro_lookup_document(table, sources) -> dict
    Write the macro lookup of a table built from base notations.
term_table_document(composition, sources, default_status) -> dict
    Write the terms of a composed glossary as a document of its contract.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Sequence, cast

import yaml

from .composition import Composition
from .issues import IssueSink
from .provenance import Source
from .records.model import Term
from .records.validation import SchemaValidator
from .typography.table import MacroTable, TargetSignature

DENOTES_TARGETS = "onomasia:denotes-targets@1"
"""Contract of the units that a key `denotes` may name, with their arguments."""

SCOPE_TABLE = "onomasia:scope-table@1"
"""Contract of the ancestors and the descendants of each audience."""

MACRO_TABLE = "onomasia:macro-table@1"
"""Contract of the macros of a composition of notations."""

MACRO_LOOKUP = "onomasia:macro-lookup@1"
"""Contract of the macro name of each unit."""

TERM_TABLE = "onomasia:term-table@1"
"""Contract of the terms of a composed glossary."""

CONTRACT_SCHEMAS = {
    DENOTES_TARGETS: "denotes-targets.schema.yml",
    SCOPE_TABLE: "scope-table.schema.yml",
    MACRO_TABLE: "macro-table.schema.yml",
    MACRO_LOOKUP: "macro-lookup.schema.yml",
    TERM_TABLE: "term-table.schema.yml",
}
"""Packaged schema of each contract."""


@dataclass(frozen=True)
class ScopeTable:
    """
    Ancestors and descendants of each audience, read from a scope table.

    Attributes
    ----------
    audiences : Mapping[str, frozenset[str]]
        Audiences related to each audience: itself, its ancestors and its descendants.
    """

    audiences: Mapping[str, frozenset[str]]

    def related(self, audience: str) -> frozenset[str]:
        """
        Audiences whose lexical rules bind a text bound to `audience`, itself included.

        Examples
        --------
        >>> ScopeTable({"ml": frozenset({"ml", "science"})}).related("ml") == {"ml", "science"}
        True
        """
        return self.audiences.get(audience, frozenset({audience}))


def _read(
    path: Path, root: Path, contract: str, validator: SchemaValidator, sink: IssueSink
) -> Mapping[str, object] | None:
    """Read and validate one input document, reporting each defect on its path."""
    resource = path.relative_to(root).as_posix() if path.is_relative_to(root) else str(path)
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as error:
        sink.report("invalid-contract", resource, "", f"cannot read the document: {error}")
        return None
    violations = list(validator.contract_errors(CONTRACT_SCHEMAS[contract], data))
    for pointer, message in violations:
        sink.report("invalid-contract", resource, pointer, message)
    return None if violations else cast(Mapping[str, object], data)


def read_signatures(
    paths: Sequence[Path], root: Path, validator: SchemaValidator, sink: IssueSink
) -> dict[str, TargetSignature]:
    """Read the arguments of each unit from documents of denotes targets, the later one winning."""
    signatures: dict[str, TargetSignature] = {}
    for path in paths:
        data = _read(path, root, DENOTES_TARGETS, validator, sink)
        for item in cast(Sequence[Mapping[str, object]], (data or {}).get("targets", ())):
            variadic = bool(item.get("variadic", False))
            binder = item.get("binder")
            signatures[str(item["target"])] = TargetSignature(
                arity=int(cast(int, item["arity"])),
                binder=int(cast(int, binder)) if binder is not None else None,
                variadic=variadic,
            )
    return signatures


def read_scope_table(
    path: Path, root: Path, validator: SchemaValidator, sink: IssueSink
) -> ScopeTable | None:
    """Read a scope table, or None when it is invalid."""
    data = _read(path, root, SCOPE_TABLE, validator, sink)
    if data is None:
        return None
    audiences = cast(Mapping[str, Mapping[str, Sequence[str]]], data["audiences"])
    return ScopeTable(
        {
            audience: frozenset({audience, *scope["ancestors"], *scope["descendants"]})
            for audience, scope in audiences.items()
        }
    )


def _header(contract: str, sources: tuple[Source, ...]) -> dict[str, object]:
    """Common fields of every document written by Onomasia."""
    return {"contract": contract, "sources": [source.to_data() for source in sources]}


def macro_table_document(table: MacroTable, sources: tuple[Source, ...]) -> dict[str, object]:
    """Write a macro table as a document of its contract."""
    document = _header(MACRO_TABLE, sources)
    document["notations"] = list(table.notations)
    document["overlays"] = list(table.overlays)
    document["entries"] = [
        {
            "id": macro.identifier,
            "notation": macro.notation,
            "target": macro.target,
            "name": macro.name,
            "body": macro.body,
            "arity": macro.arity,
            "entry": macro.entry_argument,
            "binder": macro.binder,
            "separator": macro.separator,
            "class": macro.typographic_class,
        }
        for macro in table.macros
    ]
    return document


def macro_lookup_document(table: MacroTable, sources: tuple[Source, ...]) -> dict[str, object]:
    """Write the macro lookup of a table of base notations; an undeclared entry has no row."""
    document = _header(MACRO_LOOKUP, sources)
    document["notations"] = list(table.notations)
    document["targets"] = {
        macro.target: macro.name for macro in table.macros if macro.target is not None
    }
    return document


def term_table_document(
    composition: Composition, sources: tuple[Source, ...], default_status: str
) -> dict[str, object]:
    """Write the terms of a composed glossary, sorted by identifier, as a contract document."""
    document = _header(TERM_TABLE, sources)
    document["glossary"] = composition.record.identifier
    terms: list[dict[str, object]] = []
    for identifier, visible in sorted(composition.sections.get("terms", {}).items()):
        term = visible.entry
        assert isinstance(term, Term)
        forms: list[object] = [term.label]
        forms.extend({"regex": form.text} if form.regex else form.text for form in term.forms)
        forms.extend(alternative.text for alternative in term.alternatives)
        terms.append(
            {
                "id": identifier,
                "forms": forms,
                "status": term.status or default_status,
                "gloss": {
                    "text": term.gloss,
                    "resource": visible.record.resource,
                    "pointer": f"/terms/{identifier}/gloss",
                },
            }
        )
    document["terms"] = terms
    return document
