"""
Serializations of a macro table: a LaTeX package, a MathJax preamble, and a Python expander.

Each serializer renders one table and defines each macro once, so that the three dialects print
every symbol from the same definitions. The serializers form a registry by product, through which
a new dialect joins the build without changing it.

Classes
-------
Serializer
    Protocol of a renderer of a macro table into the text of one file.

Functions
---------
latex_definitions(table) -> list[str]
    Render each macro as a definition of LaTeX.
serializer(product) -> Serializer
    Return the serializer of a product.
"""

from importlib import resources
from pathlib import Path
from string import Template
from typing import Callable, Protocol

from ..configuration import Product
from ..errors import OnomasiaError
from ..provenance import Source
from .table import Macro, MacroTable

EXPANDER_TEMPLATE = "data/expander.py.template"
"""Packaged template of the generated Python expander."""


class Serializer(Protocol):
    """Protocol of a renderer of a macro table into the text of one file."""

    def __call__(self, table: MacroTable, sources: tuple[Source, ...], path: Path) -> str:
        """Render a table, generated from its sources, as the text of the file at `path`."""


def _provenance(sources: tuple[Source, ...]) -> str:
    """State the sources of a table in one line."""
    return "; ".join(source.describe() for source in sources) or "no recorded source"


def _definition(macro: Macro) -> str:
    """Render one macro as `\\newcommand`, its entry argument optional with an empty default."""
    parameters = f"[{macro.parameters}]" if macro.parameters else ""
    optional = "[]" if macro.entry_argument else ""
    return f"\\newcommand{{\\{macro.name}}}{parameters}{optional}{{{macro.body}}}"


def latex_definitions(table: MacroTable) -> list[str]:
    """
    Render each macro as a definition of LaTeX.

    Examples
    --------
    >>> macro = Macro("w", "n", None, "W", "\\\\boldsymbol{W}_{#1}", 0, True, None, None, None)
    >>> latex_definitions(MacroTable(("n",), (), (macro,)))
    ['\\\\newcommand{\\\\W}[1][]{\\\\boldsymbol{W}_{#1}}']
    """
    return [_definition(macro) for macro in table.macros]


def latex_package(table: MacroTable, sources: tuple[Source, ...], path: Path) -> str:
    """Render a table as a LaTeX package named after its file."""
    lines = [
        f"% Generated by Onomasia from {_provenance(sources)}; do not edit.",
        "\\NeedsTeXFormat{LaTeX2e}",
        f"\\ProvidesPackage{{{path.stem}}}",
        *latex_definitions(table),
    ]
    return "\n".join(lines) + "\n"


def mathjax_preamble(table: MacroTable, sources: tuple[Source, ...], path: Path) -> str:
    """Render a table as a preamble of definitions, read by a preamble plugin of Obsidian."""
    del path  # The preamble names no package.
    return (
        "\n".join(
            [
                f"% Generated by Onomasia from {_provenance(sources)}; do not edit.",
                *latex_definitions(table),
            ]
        )
        + "\n"
    )


def python_expander(table: MacroTable, sources: tuple[Source, ...], path: Path) -> str:
    """Render a table as a Python module without dependencies, which expands its macros."""
    del path  # The module needs no name of its own.
    template = Template(
        resources.files(__package__.rsplit(".", 1)[0])
        .joinpath(EXPANDER_TEMPLATE)
        .read_text(encoding="utf-8")
    )
    macros = {
        macro.name: (macro.body, macro.parameters, macro.entry_argument) for macro in table.macros
    }
    return template.substitute(
        MACROS=repr(dict(sorted(macros.items()))),
        SOURCE_DATA=repr([source.to_data() for source in sources]),
        SOURCES=_provenance(sources),
    )


SERIALIZERS: dict[Product, Callable[[MacroTable, tuple[Source, ...], Path], str]] = {
    Product.LATEX_PACKAGE: latex_package,
    Product.MATHJAX_PREAMBLE: mathjax_preamble,
    Product.PYTHON_EXPANDER: python_expander,
}
"""Serializer of each product rendering a macro table as a file of one dialect."""


def serializer(product: Product) -> Callable[[MacroTable, tuple[Source, ...], Path], str]:
    """
    Return the serializer of a product.

    Raises
    ------
    OnomasiaError
        If the product is no serialization of a macro table.
    """
    try:
        return SERIALIZERS[product]
    except KeyError as error:
        raise OnomasiaError(f"{product.value} is no serialization of a macro table") from error
